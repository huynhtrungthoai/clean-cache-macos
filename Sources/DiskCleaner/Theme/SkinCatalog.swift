import SwiftUI

// ── Skin catalog: skin data lives in Resources/skins.json; this is its reader ─────────────
//
// A skin is a set of values, not logic. It used to be Swift `static let`s, so adding a skin meant knowing Swift
// and recompiling; now in JSON, anyone can open skins.json on GitHub's web UI, add an entry following the format,
// and open a PR. No clone, no toolchain.
//
// Reading is always lenient: missing fields take defaults, unknown enum values fall back to the default, an undecodable entry is skipped.
// If the whole file can't be read, fall back to `Theme.builtIn`. This fallback isn't fussiness: Theme is the Environment
// default, and without it the whole screen is blank, an order of magnitude worse than "ugly skin".

private func skinsJSONURL() -> URL? {
    if let u = Bundle.main.url(forResource: "skins", withExtension: "json") { return u }
    // `swift run`: Bundle.main is a bare binary in .build, so look in the source tree
    let dev = "Sources/DiskCleaner/Resources/skins.json"
    return FileManager.default.fileExists(atPath: dev) ? URL(fileURLWithPath: dev) : nil
}

// MARK: - Value helpers
//
// All return non-optional values: on failure return the fallback, so call sites needn't sprinkle ??.

private func str(_ any: Any?, _ fallback: String) -> String {
    guard let s = any as? String, !s.isEmpty else { return fallback }
    return s
}

private func num(_ any: Any?, _ fallback: Double) -> Double {
    guard let n = any as? NSNumber else { return fallback }
    return n.doubleValue
}

private func cg(_ any: Any?, _ fallback: CGFloat) -> CGFloat {
    CGFloat(num(any, Double(fallback)))
}

private func flag(_ any: Any?, _ fallback: Bool) -> Bool {
    (any as? NSNumber)?.boolValue ?? fallback
}

/// `#RRGGBB` or `#RRGGBB@opacity`. Opacity after `@` is 0–1. Falls back to fallback if unparseable.
private func color(_ any: Any?, _ fallback: Color) -> Color {
    guard let raw = any as? String else { return fallback }
    var body = raw
    var alpha: Double = 1
    if let at = raw.firstIndex(of: "@") {
        body = String(raw[raw.startIndex..<at])
        alpha = Double(raw[raw.index(after: at)...]) ?? 1
    }
    if body.hasPrefix("#") { body.removeFirst() }
    guard body.count == 6, let v = UInt(body, radix: 16) else { return fallback }
    return Color(hex: v, alpha: alpha)
}

private func colors(_ any: Any?, _ fallback: [Color]) -> [Color] {
    guard let list = any as? [Any], !list.isEmpty else { return fallback }
    let base = fallback.first ?? .gray
    let out = list.map { color($0, base) }
    // Chart series are used modulo 6 colors; too short is pointless, so fewer than one counts as unset.
    return out.count >= 2 ? out : fallback
}

/// Enum value: use it if recognized, else fall back to the default. A TYPO shouldn't make a whole skin vanish.
private func pick<T>(_ any: Any?, _ table: [String: T], _ fallback: T) -> T {
    guard let s = any as? String, let v = table[s] else { return fallback }
    return v
}

private let faces: [String: FaceDesign] = [
    "system": .system, "rounded": .rounded, "serif": .serif,
]
private let elevations: [String: Elevation] = [
    "flat": .flat, "soft": .soft, "hard": .hard, "glass": .glass,
]
private let motions: [String: MotionSignature] = [
    "still": .still, "calm": .calm, "springy": .springy,
]
private let tileShapes: [String: TileShape] = [
    "circle": .circle, "squircle": .squircle, "rounded": .rounded,
]
private let tileStrategies: [String: TileStrategy] = [
    "spectrum": .spectrum, "duotone": .duotone,
]
private let schemes: [String: ColorScheme] = [
    "light": .light, "dark": .dark,
]
/// Allowed Font.Weight values. Fewer listed because weights skins never use would just be noise in the JSON.
private let weights: [String: Font.Weight] = [
    "ultraLight": .ultraLight, "thin": .thin, "light": .light,
    "regular": .regular, "medium": .medium, "semibold": .semibold,
    "bold": .bold, "heavy": .heavy, "black": .black,
]
/// Ring material. The table is generated by `RingLook` itself, not a second hand-copied list:
/// if a new material were added and this table not synced, `pick` would silently fall that JSON line back to standard;
/// the skin still shows, the ring is still the old one, and nobody notices "the new material never reached the screen".
/// A missing key is a visible compile error; a missed copy is not.
private let ringLooks: [String: RingLook] =
    Dictionary(uniqueKeysWithValues: RingLook.allCases.map { ($0.rawValue, $0) })

// MARK: - Fallback skin

